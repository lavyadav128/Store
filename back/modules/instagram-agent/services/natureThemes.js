export function getDailyRotationalRealm(dayOffset = 0) {
  const now = new Date();
  // Deterministic daily index: calculates days since epoch so each calendar day moves to the next series in order
  const dayNumber = Math.floor(now.getTime() / (1000 * 60 * 60 * 24)) + dayOffset;
  const index = Math.abs(dayNumber) % NATURE_SERIES_LIST.length;
  return NATURE_SERIES_LIST[index];
}

export function getDailyNatureTheme(dayOffset = 0, realmCategory = null) {
  let targetRealm = realmCategory;
  if (!targetRealm || targetRealm === "All Realms" || targetRealm === "all") {
    targetRealm = getDailyRotationalRealm(dayOffset);
  }

  let filtered = NATURE_THEMES.filter(
    (t) => t.realm.toLowerCase().includes(targetRealm.toLowerCase()) ||
           targetRealm.toLowerCase().includes(t.realm.toLowerCase())
  );
  if (filtered.length === 0) filtered = NATURE_THEMES;

  const todayIndex = (new Date().getDate() + dayOffset) % filtered.length;
  return filtered[todayIndex];
}

export function getUniqueNatureTheme(usedFingerprints = new Set(), realmCategory = null) {
  let targetRealm = realmCategory;
  if (!targetRealm || targetRealm === "All Realms" || targetRealm === "all") {
    targetRealm = getDailyRotationalRealm();
  }

  let filtered = NATURE_THEMES.filter(
    (t) => t.realm.toLowerCase().includes(targetRealm.toLowerCase()) ||
           targetRealm.toLowerCase().includes(t.realm.toLowerCase())
  );
  if (filtered.length === 0) filtered = NATURE_THEMES;

  for (const theme of filtered) {
    if (!usedFingerprints.has(theme.id) && !usedFingerprints.has(theme.title)) {
      return theme;
    }
  }

  return filtered[Math.floor(Math.random() * filtered.length)];
}
