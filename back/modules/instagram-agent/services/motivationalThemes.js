/**
 * Normalizes quote string for fingerprinting and uniqueness checking
 */
export function getQuoteFingerprint(text = "") {
  return String(text || "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "")
    .slice(0, 60);
}

/**
 * Returns a unique motivational theme avoiding previously published or drafted quotes.
 * Rotates through the 5 pillars based on audience growth performance.
 */
export function getUniqueMotivationalTheme(usedFingerprints = new Set(), audienceTopCategory = null) {
  let themes = [...MOTIVATIONAL_THEMES];

  // 1. Prioritize audience top category if provided
  if (audienceTopCategory) {
    const preferred = themes.filter(
      (t) => t.category.toLowerCase() === audienceTopCategory.toLowerCase()
    );
    if (preferred.length > 0) {
      themes = [...preferred, ...themes];
    }
  }

  // 2. Filter out already used themes
  const freshThemes = themes.filter((t) => {
    const fp = getQuoteFingerprint(t.quote);
    return !usedFingerprints.has(fp);
  });

  // 3. If all static themes have been used, pick the oldest one or cycle with variation
  const pool = freshThemes.length > 0 ? freshThemes : themes;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

export function getDailyMotivationalTheme(dayOffset = 0, audienceTopCategory = null) {
  return getUniqueMotivationalTheme(new Set(), audienceTopCategory);
}
