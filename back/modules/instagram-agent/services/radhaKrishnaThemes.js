/**
 * Returns a unique theme based on day-of-year offset and audience feedback weighting
 */
export function getDailyRadhaKrishnaTheme(dayOffset = 0, audienceTopCategory = null) {
  let themes = [...RADHA_KRISHNA_THEMES];

  // If audience analytics show high preference for a category (e.g. Divine Love or Flute), boost that category
  if (audienceTopCategory) {
    const preferred = themes.filter(t => t.category.toLowerCase() === audienceTopCategory.toLowerCase());
    if (preferred.length > 0) {
      themes = [...preferred, ...themes];
    }
  }

  const today = new Date();
  const dayOfYear = Math.floor((today - new Date(today.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24)) + dayOffset;
  const selectedIndex = dayOfYear % themes.length;
  return themes[selectedIndex];
}
